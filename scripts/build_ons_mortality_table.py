"""Build src/ukMortalityTable.js from the ONS projected life tables.

Source: ONS, "Mortality rates (qx), principal projection, United Kingdom"
(Past and projected period and cohort life tables, 2024-based, UK), file
ukppp24qx.xlsx from
https://www.ons.gov.uk/peoplepopulationandcommunity/birthsdeathsandmarriages/lifeexpectancies/datasets/mortalityratesqxprincipalprojectionunitedkingdom

For each sex and year of birth it writes cohort mortality rates qx (the chance
of dying between exact ages x and x+1) from age max(16, 1981 - birth year) to
100, plus a Kannisto curve fitted to ages 90-100 for extrapolating beyond 100.

  * Born 1981 or later: the ONS cohort table, which already allows for
    projected improvements, including beyond the last projected year.
  * Born earlier: the cohort is read off the period table's diagonal (age x in
    calendar year birth + x), which is how ONS builds cohort tables and matches
    them exactly where both exist. Past the last period year, rates improve at
    the same yearly rate by age that the ONS 1981 cohort implies.

Usage (needs openpyxl):  python3 scripts/build_ons_mortality_table.py ukppp24qx.xlsx
When ONS publishes a new edition, update SOURCE below and rerun.
"""

import math
import sys
from pathlib import Path

import openpyxl

FIRST_BIRTH_YEAR = 1920
LAST_BIRTH_YEAR = 2010
MIN_AGE = 16
MAX_DATA_AGE = 100
FIT_AGES = range(90, 101)  # ages used for the Kannisto tail fit
SOURCE = {
    'title': 'Past and projected period and cohort life tables, 2024-based, UK: 1981 to 2074',
    'dataset': 'Mortality rates (qx), principal projection, United Kingdom',
    'file': 'ukppp24qx.xlsx',
    'released': '2026-05-15',
    'url': 'https://www.ons.gov.uk/peoplepopulationandcommunity/birthsdeathsandmarriages/lifeexpectancies/datasets/mortalityratesqxprincipalprojectionunitedkingdom',
}
OUT = Path(__file__).resolve().parent.parent / 'src' / 'ukMortalityTable.js'


def load_sheet(wb, name):
    rows = list(wb[name].iter_rows(values_only=True))
    hdr = next(i for i, r in enumerate(rows) if isinstance(r[0], str) and r[0].startswith('Exact age'))
    years = [int(str(h).split()[-1]) for h in rows[hdr][1:] if h is not None]
    qx = {}
    for r in rows[hdr + 1:]:
        if not isinstance(r[0], (int, float)):
            continue
        # ONS publishes rates per 100,000; convert to probabilities.
        qx[int(r[0])] = {y: float(v) / 100_000 for y, v in zip(years, r[1:]) if v is not None}
    return qx


def cohort_rates(period, cohort, birth_year):
    """qx by age for one birth year, from the start age to MAX_DATA_AGE."""
    start = max(MIN_AGE, 1981 - birth_year)
    last_year = max(period[0])
    out = []
    for age in range(start, MAX_DATA_AGE + 1):
        if birth_year >= 1981:
            q = cohort[age][birth_year]
        elif birth_year + age <= last_year:
            q = period[age][birth_year + age]
        else:
            # Beyond the last projected year: improve at the yearly rate by age
            # implied by the ONS 1981 cohort relative to the last period year.
            years_on = 1981 + age - last_year
            rate = (cohort[age][1981] / period[age][last_year]) ** (1 / years_on)
            q = period[age][last_year] * rate ** (birth_year + age - last_year)
        out.append(q)
    return start, out


def kannisto_fit(start, rates):
    """Least-squares fit of logit(mu) = ln a + b x on FIT_AGES (mu = -ln(1 - q))."""
    xs, ys = [], []
    for x in FIT_AGES:
        mu = -math.log(1 - rates[x - start])
        xs.append(x)
        ys.append(math.log(mu / (1 - mu)))
    n = len(xs)
    mx, my = sum(xs) / n, sum(ys) / n
    b = sum((x - mx) * (y - my) for x, y in zip(xs, ys)) / sum((x - mx) ** 2 for x in xs)
    return my - b * mx, b


def main(path):
    wb = openpyxl.load_workbook(path, read_only=True, data_only=True)
    tables = {}
    for sex in ('male', 'female'):
        period = load_sheet(wb, f'{sex}s period qx')
        cohort = load_sheet(wb, f'{sex}s cohort qx')
        rows = []
        for by in range(FIRST_BIRTH_YEAR, LAST_BIRTH_YEAR + 1):
            start, rates = cohort_rates(period, cohort, by)
            ln_a, b = kannisto_fit(start, rates)
            per_million = ','.join(str(round(q * 1_000_000)) for q in rates)
            rows.append(f'    [{start}, {ln_a:.6f}, {b:.6f}, {per_million}],')
        tables[sex] = '\n'.join(rows)

    src = f"""// Generated by scripts/build_ons_mortality_table.py — do not edit by hand.
//
// Cohort mortality rates for the UK from the ONS projected life tables. Each
// row is one year of birth, from firstBirthYear: [startAge, kannistoLnA,
// kannistoB, qx per million at startAge, startAge + 1, …, {MAX_DATA_AGE}].
// See ukMortality.js for how the rows are used.

export const ONS_MORTALITY_SOURCE = {{
  title: '{SOURCE['title']}',
  dataset: '{SOURCE['dataset']}',
  file: '{SOURCE['file']}',
  released: '{SOURCE['released']}',
  url: '{SOURCE['url']}',
}};

export const COHORT_TABLE = {{
  firstBirthYear: {FIRST_BIRTH_YEAR},
  lastBirthYear: {LAST_BIRTH_YEAR},
  maxDataAge: {MAX_DATA_AGE},
  male: [
{tables['male']}
  ],
  female: [
{tables['female']}
  ],
}};
"""
    OUT.write_text(src)
    print(f'wrote {OUT} ({len(src) // 1024} KB)')


if __name__ == '__main__':
    main(sys.argv[1])
